def format_price(amount: Union[int, float, str, None]) -> str:
    """
    فرمت‌بندی قیمت به صورت ۳ رقم ۳ رقم با تومان.
    ورودی می‌تواند int, float, str یا Decimal باشد.
    """
    try:
        if not amount: 
            return "<code>0</code> تومان"
        
        # تبدیل انواع مختلف عددی به float و سپس int برای حذف اعشار غیرضروری
        val = int(float(amount))
        return f"<b>{val:,}</b> تومان"
    except (ValueError, TypeError):
        return "<code>0</code> تومان"

def get_divider() -> str:
    """جداکننده گرافیکی برای نظم‌دهی به پیام‌ها"""
    return "\n\n─── • ⚪️ • ───\n\n"

def get_progress_bar(current_step: int, total_steps: int = 3) -> str:
    """ایجاد نوار پیشرفت برای مراحل خرید"""
    bar = ""
    for i in range(1, total_steps + 1):
        if i < current_step: bar += "🟢"  # مرحله طی شده
        elif i == current_step: bar += "🟠" # مرحله فعلی
        else: bar += "⚪️" # مرحله باقی‌مانده
    return f"<b>مرحله {current_step} از {total_steps}</b>\n{bar}"

def get_tracking_timeline(status: str) -> str:
    """نمودار گرافیکی وضعیت سفارش (Timeline)"""
    steps = {
        "pending_payment": ("🔸", "◽️", "◽️", "◽️"), # در انتظار پرداخت
        "approved":        ("✅", "🔸", "◽️", "◽️"), # تایید شده
        "shipped":         ("✅", "✅", "✅", "🚚"), # ارسال شده
        "rejected":        ("❌", "─", "─", "─"),    # رد شده
        "paid":            ("✅", "✅", "◽️", "◽️")  # پرداخت شده
    }
    s = steps.get(status, ("◽️", "◽️", "◽️", "◽️"))
    
    timeline = (
        f"{s[0]} <b>ثبت سفارش</b>\n"
        f"   └ {s[1]} <b>تایید مالی</b>\n"
        f"      └ {s[2]} <b>آماده‌سازی</b>\n"
        f"         └ {s[3]} <b>تحویل پست</b>"
    )
    return timeline

